#!/usr/bin/env python3
"""KB_CI mode of backend/src/kb/lint/lint.py.

A cloud checkout has `meta/corpus.tsv` but not the raw binaries it lists (gitignored PDFs/PNGs).
Fixture choice: a tiny temp vault (one paper page citing one raw PDF that is absent from disk but
present in the manifest) with `lint.ROOT` / `coherence` paths monkeypatched, rather than a copy
of the real repo — `collect_snapshot` is the real entry point, so the seams are exercised
end to end without 600 raw files.
"""
import contextlib
import io
import os
import shutil
import sys
import tempfile
import unittest
from unittest import mock

from kb.core import coherence
from kb.lint import lint

RAW = "raw/printed-docs/2023-toolformer.pdf"
PAGE = """---
type: paper
layer: source
status: digested
depth: full
year: 2023
area: [learning-theory]
raw: raw/printed-docs/2023-toolformer.pdf
---
# Toolformer

LLMs teach themselves to call tools.

## Problem
x
"""
MANIFEST = ("# Generated by backend/src/kb/lint/lint.py.\n"
            "path\tsha1\tkind\tdisposition\tslug\tcollection\n"
            f"{RAW}\tdbb0b0eede69\tprinted-docs\tsource\tpaper-toolformer\t\n")


class LintCiTest(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp(prefix="kb-ci-")
        os.makedirs(os.path.join(self.root, "wiki"))
        os.makedirs(os.path.join(self.root, "meta"))
        os.makedirs(os.path.join(self.root, "raw", "printed-docs"))
        with open(os.path.join(self.root, "wiki", "paper-toolformer.md"), "w", encoding="utf-8") as f:
            f.write(PAGE)
        with open(os.path.join(self.root, "meta", "corpus.tsv"), "w", encoding="utf-8") as f:
            f.write(MANIFEST)
        self.patches = [
            mock.patch.object(lint, "ROOT", self.root),
            mock.patch.object(coherence, "ROOT", self.root),
            mock.patch.object(coherence, "WARNINGS_PATH",
                              os.path.join(self.root, "meta", "coherence-warnings.tsv")),
        ]
        for p in self.patches:
            p.start()

    def tearDown(self):
        for p in self.patches:
            p.stop()
        lint.CI_RAW.clear()
        shutil.rmtree(self.root, ignore_errors=True)

    def _run(self, env):
        out = io.StringIO()
        with mock.patch.dict(os.environ, env, clear=False), contextlib.redirect_stdout(out):
            snap = lint.collect_snapshot()
        return snap, out.getvalue()

    def test_ci_mode_passes_without_raw_bytes(self):
        snap, out = self._run({"KB_CI": "1"})
        self.assertEqual(snap["values"]["errors"], 0, lint.errors)
        self.assertIn("partial checkout:", out)
        self.assertIn("wrote index.md", out)                     # a partial checkout still regenerates
        with open(os.path.join(self.root, "meta", "corpus.tsv"), encoding="utf-8") as f:
            self.assertIn(RAW, f.read(), "the missing binary keeps its manifest row under KB_CI")
        self.assertEqual(snap["_rows"][RAW]["disposition"], "source")

    def test_default_mode_detects_missing_raw(self):
        env = dict(os.environ)
        env.pop("KB_CI", None)
        with mock.patch.dict(os.environ, env, clear=True):
            snap, out = self._run({})
        self.assertTrue(any(f"raw: {RAW} does not exist on disk" in e for e in lint.errors), lint.errors)
        self.assertNotIn("KB_CI:", out)
        self.assertIn("wrote index.md", out)
        self.assertNotIn(RAW, snap["_rows"], "reconcile drops a manifest row whose file is gone")


if __name__ == "__main__":
    unittest.main()
