def build_inputs(inputs):
    inputs = Path(inputs)
    inputs.mkdir(parents=True, exist_ok=True)
    _pdf(inputs / CASES["source-paper-arxiv-style"], 3, "Fixture arXiv-style paper",
         stamp="arXiv:2105.10386v1 [cs.LG] 21 May 2021")
    _pdf(inputs / CASES["source-paper-local"], 3, "Fixture local paper")
    (inputs / CASES["source-article-web-clip"]).write_text(_CLIP.replace("{{", "{").replace("}}", "}"), encoding="utf-8")
    (inputs / CASES["source-blog-post-hebrew"]).write_text(_HEBREW.replace("{{", "{").replace("}}", "}"), encoding="utf-8")
    (inputs / CASES["source-ai-chat"]).write_text(_CHAT, encoding="utf-8")
    (inputs / CASES["source-conversation-email"]).write_text(_MBOX, encoding="utf-8")
    chapters = [("Chapter 1. Foundations", 1), ("Chapter 2. Concentration", 16),
                ("Chapter 3. Learning", 31), ("Chapter 4. Applications", 47)]
    _pdf(inputs / CASES["collection-book"], 62, "Fixture book",
         toc=[[1, name, page] for name, page in chapters])
    _pdf(inputs / CASES["collection-course-member-1"], 3, "Fixture RL lecture 1")
    _pdf(inputs / CASES["collection-course-member-2"], 3, "Fixture RL lecture 2")
    return {k: str(inputs / v) for k, v in CASES.items()}


# ---------------------------------------------------------------- the vault

def build(root, inputs):
    """Create the scratch vault at `root` (must not exist) and the input files at `inputs`."""
    root = Path(root)
    pages = seed_pages()
    root.mkdir(parents=True)
    meta = root / "meta"
    meta.mkdir()
    shutil.copytree(CODE_SRC, root / "src" / "kb_distillery", ignore=CODE_IGNORE)
    for name in META_COPY:
        if (META_SRC / name).is_dir():
            shutil.copytree(META_SRC / name, meta / name, ignore=CODE_IGNORE)
    (root / "kb.toml").write_text('[kb]\nid = "harness"\nname = "Harness fixture vault"\nschema_version = "1.6"\n'
                                  '\n[types]\nareas = [' + ", ".join(f'"{t}"' for t in TOPICS) + ']\n', encoding="utf-8")
    (meta / "corpus.tsv").write_text(MANIFEST_HEADER, encoding="utf-8")
    (meta / "aliases.tsv").write_text("", encoding="utf-8")
    (meta / "thesis.md").write_text("# Thesis\n\nFixture.\n", encoding="utf-8")
    (meta / "coherence-warnings.tsv").write_text("id\tscore\tkind\tslugs\tsummary\tstatus\n", encoding="utf-8")
    (root / "wiki").mkdir()
    (root / "wiki" / "log.md").write_text("# Log\n", encoding="utf-8")
    for slug, text in pages.items():
        (root / "wiki" / f"{slug}.md").write_text(text, encoding="utf-8")
    for d in RAW_DIRS:
        (root / "raw" / d).mkdir(parents=True)
    (root / "think").mkdir()
    (root / "think" / ".keep").write_text("", encoding="utf-8")
    for name in ("AGENTS.md", "CLAUDE.md", "README.md"):
        (root / name).write_text(f"# {name}\n", encoding="utf-8")
    return build_inputs(inputs)
