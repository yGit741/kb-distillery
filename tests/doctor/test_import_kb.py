def test_kit_lint_findings_warn_but_only_okf_blocks(world, tmp_path):
    """The OKF check is the gate; the stricter kit lint runs in the dry run and the import alike and its findings are
    warnings, so a valid OKF bundle with types the kit does not know imports as written."""
    src = make_bundle(tmp_path / "kitbad", {"a.md": "---\ntype: not-a-kit-type\n---\n# A\n\nhi\n"})
    rep = import_kb.validate_bundle(src)                 # passes okf_check, the kit lint finds the type
    assert rep.ok
    assert any("not-a-kit-type" in w for w in rep.warnings)
    assert any("ops` commits in this kb are refused" in w for w in rep.warnings)   # the consequence is said up front
    target = import_kb.import_bundle(src)
    with open(os.path.join(target, "wiki", "a.md"), encoding="utf-8") as f:
        assert "type: not-a-kit-type" in f.read()        # imported as written
    bad = make_bundle(tmp_path / "okfbad", {"a.md": "---\ntype: idea\n---\n# A\n\n[gone](gone.md)\n"})
    assert not import_kb.validate_bundle(bad).ok         # an OKF finding still blocks
    with pytest.raises(import_kb.BundleError):
        import_kb.import_bundle(bad, kb_id="okfbad")


def test_bundle_root_links_are_rewritten_relative(world, tmp_path):
    """A bundle written with `/slug.md` links (its `/` meaning the bundle root) imports with plain `slug.md` links; the
    source folder is left as it was, the dry run reports the rewrite as a warning, and a missing target still blocks."""
    alpha = PAGE.replace("[beta](beta.md)", "[beta](/beta.md#beta) and ![img](/pic.png)")
    src = make_bundle(tmp_path / "rooted", {"alpha.md": alpha, "beta.md": BETA})
    rep = import_kb.validate_bundle(src)
    assert rep.errors == []
    assert any("rewritten" in w for w in rep.warnings)
    target = import_kb.import_bundle(src)
    with open(os.path.join(target, "wiki", "alpha.md"), encoding="utf-8") as f:
        text = f.read()
    assert "[beta](beta.md#beta)" in text and "](/beta.md" not in text
    assert "![img](/pic.png)" in text                       # images and missing targets are not touched
    with open(os.path.join(src, "alpha.md"), encoding="utf-8") as f:
        assert "[beta](/beta.md#beta)" in f.read()          # the source is not changed

    broken = make_bundle(tmp_path / "broken", {"alpha.md": PAGE.replace("[beta](beta.md)", "[gone](/gone.md)"), "beta.md": BETA})
    assert any("unresolved: /gone.md" in e for e in import_kb.validate_bundle(broken).errors)


def test_raw_and_sibling_folders_come_with_the_bundle(world, tmp_path):
    src = tmp_path / "kbsrc"
    make_bundle(src / "wiki", {"alpha.md": PAGE.replace("See [beta](beta.md).", "From [notes](../raw/notes.md) and [x](/raw/x.md); "
                                                       "run [demo](../examples/demo.py), see [card](../usecase.md)."), "beta.md": BETA})
    os.makedirs(src / "raw")
    (src / "raw" / "notes.md").write_text("notes\n")
    (src / "raw" / "x.md").write_text("x\n")
    os.makedirs(src / "examples")
    (src / "examples" / "demo.py").write_text("print(1)\n")
    (src / "README.md").write_text("not knowledge\n")
    (src / "usecase.md").write_text("card\n")
    rep = import_kb.validate_bundle(str(src))
    assert rep.errors == []
    assert any("raw/" in w and "examples/" in w for w in rep.warnings)
    target = import_kb.import_bundle(str(src))
    assert os.path.isfile(os.path.join(target, "raw", "notes.md"))
    assert os.path.isfile(os.path.join(target, "raw", "examples", "demo.py"))
    assert "../raw/examples/demo.py" in open(os.path.join(target, "wiki", "alpha.md"), encoding="utf-8").read()
    assert os.path.isfile(os.path.join(target, "raw", "usecase.md"))
    assert "not knowledge" not in open(os.path.join(target, "README.md"), encoding="utf-8").read()
    tracked = subprocess.run(["git", "ls-files"], cwd=target, capture_output=True, text=True).stdout
    assert "raw/notes.md" in tracked and "raw/examples/demo.py" in tracked


