"""distill kb import: an OKF bundle (folder or zip) becomes a new kb. Temp dirs only; never ~/knowledge."""
import os
import subprocess
import zipfile

import pytest

from kb_distillery import import_kb, llm
from kb_distillery.config import kb as kbconfig

PAGE = "---\ntype: idea\nlayer: concept\nmaturity: seed\n---\n# Alpha\n\nSee [beta](beta.md).\n"
BETA = "---\ntype: idea\nlayer: concept\nmaturity: seed\n---\n# Beta\n\nBack to [alpha](alpha.md).\n"


@pytest.fixture
def world(monkeypatch, tmp_path):
    home = tmp_path / "home"
    home.mkdir()
    bases = tmp_path / "kbs"
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("KB_BASES_DIR", str(bases))
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", os.devnull)
    monkeypatch.setenv("GIT_CONFIG_NOSYSTEM", "1")
    for k in ("KB", "KB_ROOT", "GIT_AUTHOR_NAME", "GIT_AUTHOR_EMAIL", "GIT_COMMITTER_NAME", "GIT_COMMITTER_EMAIL"):
        monkeypatch.delenv(k, raising=False)
    monkeypatch.setattr(llm, "KEY_FILE", str(tmp_path / "nokey"))
    monkeypatch.setattr(llm, "_which", lambda n: None)
    return bases


def make_bundle(root, pages=None):
    os.makedirs(root, exist_ok=True)
    for name, text in (pages or {"alpha.md": PAGE, "beta.md": BETA}).items():
        with open(os.path.join(root, name), "w", encoding="utf-8") as f:
            f.write(text)
    return str(root)


def zip_dir(folder, zpath, prefix=""):
    with zipfile.ZipFile(zpath, "w") as z:
        for base, _d, files in os.walk(folder):
            for n in files:
                full = os.path.join(base, n)
                z.write(full, prefix + os.path.relpath(full, folder))
    return str(zpath)


def git(path, *args):
    return subprocess.run(["git", *args], cwd=path, capture_output=True, text=True, check=True).stdout.strip()


def test_folder_import(world, tmp_path):
    src = make_bundle(tmp_path / "my-notes")
    target = import_kb.import_bundle(src)
    assert target == str(world / "my-notes")
    assert kbconfig.load_dir(target).id == "my-notes"
    assert os.path.isfile(os.path.join(target, "wiki", "alpha.md"))
    assert os.path.isfile(os.path.join(target, "wiki", "index.md"))        # regenerated by the engine's lint
    assert git(target, "status", "--porcelain") == ""
    assert git(target, "log", "-1", "--format=%s").startswith("kb(import):")


