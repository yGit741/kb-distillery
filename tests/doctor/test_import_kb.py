def test_git_source_is_a_one_time_copy(world, tmp_path, monkeypatch):
    seen = {}

    def fake_clone(url, ref, dest):
        seen.update(url=url, ref=ref)
        make_bundle(os.path.join(dest, "wiki"))
        os.makedirs(os.path.join(dest, ".git"))
        with open(os.path.join(dest, ".git", "config"), "w") as f:
            f.write("[remote \"origin\"]\n")
        return "abc123"

    monkeypatch.setattr(import_kb, "_clone", fake_clone)
    target = import_kb.import_bundle("https://example.com/me/notes.git#v1")
    assert seen == {"url": "https://example.com/me/notes.git", "ref": "v1"}
    assert target == str(world / "notes")
    assert git(target, "remote") == ""                                    # fresh history, no origin
    assert not os.path.exists(os.path.join(target, "wiki", ".git"))
    assert git(target, "status", "--porcelain") == ""
    imp = kbconfig.load_dir(target).section("import")
    assert imp["source"] == "https://example.com/me/notes.git" and imp["ref"] == "v1" and imp["commit"] == "abc123"
    assert imp["imported_at"].endswith("Z")


def test_dry_run_reports_and_writes_nothing(world, tmp_path, capsys):
    good = make_bundle(tmp_path / "good")
    rep = import_kb.validate_bundle(good)
    assert (rep.id, rep.pages, rep.errors, rep.ok) == ("good", 2, [], True)
    bad = make_bundle(tmp_path / "bad", {"a.md": "# no type\n"})
    rep = import_kb.validate_bundle(bad, kb_id="x")
    assert not rep.ok and any("type" in e for e in rep.errors)
    assert import_kb.main([good, "--dry-run"]) == 0
    assert import_kb.main([bad, "--dry-run"]) == 1
    assert not world.exists() or not os.listdir(world)


def test_dry_run_with_errors_prints_only_the_errors_and_exits_1(world, tmp_path, capsys):
    bad = make_bundle(tmp_path / "bad-notes", {"a.md": PAGE.replace("beta.md", "missing.md"), "b.md": BETA})
    assert import_kb.main([bad, "--dry-run"]) == 1
    out, err = capsys.readouterr()
    assert "missing.md" in err
    assert "would import" not in out + err
    lines = out.strip().splitlines()
    assert len(lines) == 1 and lines[0].startswith("nothing would be imported:")
    capsys.readouterr()
    assert import_kb.main([make_bundle(tmp_path / "ok"), "--dry-run"]) == 0
    assert capsys.readouterr().out.startswith("would import 2 page(s)")


