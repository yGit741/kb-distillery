"""distill kb import: an OKF bundle (folder or zip) becomes a new kb. Temp dirs only; never ~/knowledge."""
import os
import subprocess
import zipfile

import pytest

from kb_distillery import import_kb, llm
from kb_distillery.config import kb as kbconfig

PAGE = "---\ntype: idea\nlayer: concept\nmaturity: seed\n---\n# Alpha\n\nSee [beta](beta.md).\n"
BETA = "---\ntype: idea\nlayer: concept\nmaturity: seed\n---\n# Beta\n\nBack to [alpha](alpha.md).\n"


@pytest.fixture
def world(monkeypatch, tmp_path):
    home = tmp_path / "home"
    home.mkdir()
    bases = tmp_path / "kbs"
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("KB_BASES_DIR", str(bases))
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", os.devnull)
    monkeypatch.setenv("GIT_CONFIG_NOSYSTEM", "1")
    for k in ("KB", "KB_ROOT", "GIT_AUTHOR_NAME", "GIT_AUTHOR_EMAIL", "GIT_COMMITTER_NAME", "GIT_COMMITTER_EMAIL"):
        monkeypatch.delenv(k, raising=False)
    monkeypatch.setattr(llm, "KEY_FILE", str(tmp_path / "nokey"))
    monkeypatch.setattr(llm, "_which", lambda n: None)
    return bases


def make_bundle(root, pages=None):
    os.makedirs(root, exist_ok=True)
    for name, text in (pages or {"alpha.md": PAGE, "beta.md": BETA}).items():
        with open(os.path.join(root, name), "w", encoding="utf-8") as f:
            f.write(text)
    return str(root)


def zip_dir(folder, zpath, prefix=""):
    with zipfile.ZipFile(zpath, "w") as z:
        for base, _d, files in os.walk(folder):
            for n in files:
                full = os.path.join(base, n)
                z.write(full, prefix + os.path.relpath(full, folder))
    return str(zpath)


def git(path, *args):
    return subprocess.run(["git", *args], cwd=path, capture_output=True, text=True, check=True).stdout.strip()


def test_folder_import(world, tmp_path):
    src = make_bundle(tmp_path / "my-notes")
    target = import_kb.import_bundle(src)
    assert target == str(world / "my-notes")
    assert kbconfig.load_dir(target).id == "my-notes"
    assert os.path.isfile(os.path.join(target, "wiki", "alpha.md"))
    assert os.path.isfile(os.path.join(target, "wiki", "index.md"))        # regenerated by the engine's lint
    assert git(target, "status", "--porcelain") == ""
    assert git(target, "log", "-1", "--format=%s").startswith("kb(import):")


def test_wiki_subfolder_and_explicit_id_and_kit(world, tmp_path):
    make_bundle(tmp_path / "pkg" / "wiki")
    target = import_kb.import_bundle(str(tmp_path / "pkg"), kit="research", kb_id="other")
    assert target == str(world / "other")
    assert kbconfig.load_dir(target).kit == "research"
    assert os.path.isfile(os.path.join(target, "wiki", "beta.md"))


def test_zip_import_with_single_top_folder(world, tmp_path):
    make_bundle(tmp_path / "src" / "bundle")
    z = zip_dir(tmp_path / "src", tmp_path / "bundle.zip")
    target = import_kb.import_bundle(z)
    assert target == str(world / "bundle")
    assert os.path.isfile(os.path.join(target, "wiki", "alpha.md"))


def test_zip_slip_rejected(world, tmp_path):
    z = tmp_path / "evil.zip"
    with zipfile.ZipFile(z, "w") as zf:
        zf.writestr("alpha.md", PAGE)
        zf.writestr("../escaped.md", PAGE)
    with pytest.raises(import_kb.BundleError, match="unsafe"):
        import_kb.import_bundle(str(z))
    assert not (tmp_path / "escaped.md").exists()
    assert not world.exists() or not os.listdir(world)


def test_zip_absolute_and_symlink_rejected(world, tmp_path):
    z = tmp_path / "abs.zip"
    with zipfile.ZipFile(z, "w") as zf:
        zf.writestr("/abs.md", PAGE)
    with pytest.raises(import_kb.BundleError, match="unsafe"):
        import_kb.import_bundle(str(z))
    z2 = tmp_path / "link.zip"
    with zipfile.ZipFile(z2, "w") as zf:
        info = zipfile.ZipInfo("link.md")
        info.external_attr = (0o120777 << 16)
        zf.writestr(info, "/etc/passwd")
    with pytest.raises(import_kb.BundleError, match="symlink"):
        import_kb.import_bundle(str(z2))


def test_invalid_bundle_writes_nothing(world, tmp_path):
    src = make_bundle(tmp_path / "bad", {"alpha.md": "---\ntype: idea\nlayer: concept\nmaturity: seed\n---\n# A\n\n[gone](missing.md)\n", "b.md": "# no type\n"})
    with pytest.raises(import_kb.BundleError, match="not valid OKF") as e:
        import_kb.import_bundle(src)
    assert "missing.md" in str(e.value) and "type" in str(e.value)
    assert not world.exists() or not os.listdir(world)


def test_duplicate_id_refused(world, tmp_path):
    src = make_bundle(tmp_path / "dup")
    import_kb.import_bundle(src)
    with pytest.raises(import_kb.BundleError, match="already exists"):
        import_kb.import_bundle(src)
    assert os.listdir(world) == ["dup"]


def test_cli_exit_codes(world, tmp_path, capsys):
    assert import_kb.main([make_bundle(tmp_path / "ok")]) == 0
    assert import_kb.main([str(tmp_path / "missing")]) == 1
    assert "does not exist" in capsys.readouterr().err


def test_git_source_is_a_one_time_copy(world, tmp_path, monkeypatch):
    seen = {}

    def fake_clone(url, ref, dest):
        seen.update(url=url, ref=ref)
        make_bundle(os.path.join(dest, "wiki"))
        os.makedirs(os.path.join(dest, ".git"))
        with open(os.path.join(dest, ".git", "config"), "w") as f:
            f.write("[remote \"origin\"]\n")
        return "abc123"

    monkeypatch.setattr(import_kb, "_clone", fake_clone)
    target = import_kb.import_bundle("https://example.com/me/notes.git#v1")
    assert seen == {"url": "https://example.com/me/notes.git", "ref": "v1"}
    assert target == str(world / "notes")
    assert git(target, "remote") == ""                                    # fresh history, no origin
    assert not os.path.exists(os.path.join(target, "wiki", ".git"))
    assert git(target, "status", "--porcelain") == ""
    imp = kbconfig.load_dir(target).section("import")
    assert imp["source"] == "https://example.com/me/notes.git" and imp["ref"] == "v1" and imp["commit"] == "abc123"
    assert imp["imported_at"].endswith("Z")


def test_dry_run_reports_and_writes_nothing(world, tmp_path, capsys):
    good = make_bundle(tmp_path / "good")
    rep = import_kb.validate_bundle(good)
    assert (rep.id, rep.pages, rep.errors, rep.ok) == ("good", 2, [], True)
    bad = make_bundle(tmp_path / "bad", {"a.md": "# no type\n"})
    rep = import_kb.validate_bundle(bad, kb_id="x")
    assert not rep.ok and any("type" in e for e in rep.errors)
    assert import_kb.main([good, "--dry-run"]) == 0
    assert import_kb.main([bad, "--dry-run"]) == 1
    assert not world.exists() or not os.listdir(world)


@pytest.mark.flag("kb-view", True)
def test_imported_kb_works_in_graph_and_page_reader(world, tmp_path):
    from fastapi.testclient import TestClient

    from kb_distillery.server.app import create_app
    from kb_distillery.services import kbview
    import_kb.import_bundle(make_bundle(tmp_path / "wikis"), kb_id="viewme")
    kbview._views.clear()
    with TestClient(create_app()) as c:
        g = c.get("/api/graph?kb=viewme").json()
        assert sorted(n["id"] for n in g["nodes"]) == ["alpha", "beta"]
        assert {"alpha", "beta"} == {l["source"] for l in g["links"]} & {"alpha", "beta"}
        r = c.get("/api/pages/alpha?kb=viewme")
        assert r.status_code == 200
        page = r.json()
        assert page["outbound"] == ["beta"] and page["broken"] == []
        assert "[beta](beta.md)" in page["markdown"] or "beta" in page["markdown"]
        assert [b["id"] for b in page["backlinks"]] == ["beta"]
    kbview._views.clear()
