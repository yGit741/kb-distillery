// Bundle web/src/lib/okf/checkBundle.ts (+ js-yaml) into one dependency-free ES module for the Worker, so the site
// validates an upload with the very checker the browser uses.
//
//   node build-okf.mjs <out.js>        pixi run worker-bundle   (writes ./okf.gen.js, git-ignored)
//
// esbuild comes from web/node_modules (a dependency of vite): `pixi run web-install` first. The deploy
// (`deploy.render_worker_dir`) runs this into the temporary Worker folder, so a deployed Worker is never older than its
// checker; `test-worker` runs it first (the CI `worker` job runs `web-install` before), so the inbox tests run against the real bundle.
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../../../..");
const out = resolve(process.argv[2] || join(here, "okf.gen.js"));
const esbuildEntry = join(root, "web/node_modules/esbuild/lib/main.js");
if (!existsSync(esbuildEntry)) {
  console.error("build-okf: web/node_modules/esbuild is missing; run `pixi run web-install` first");
  process.exit(2);
}
const { build } = await import(pathToFileURL(esbuildEntry).href);
await build({
  entryPoints: [join(here, "okf.entry.js")], outfile: out, bundle: true, format: "esm", platform: "neutral",
  target: "es2022", banner: { js: "// GENERATED by build-okf.mjs from web/src/lib/okf: do not edit, do not commit." },
  logLevel: "error",
});
console.log(`build-okf: wrote ${out}`);
