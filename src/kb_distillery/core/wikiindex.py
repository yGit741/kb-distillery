"""The generated wiki index: a tiny root plus one section index per page type.

A query used to read one flat `wiki/index.md` (280 KB on a 1,100-page kb). Now it reads the root (about 1 KB: one line
per type with its page count) and then only the section it needs:

    wiki/index.md                      root: `okf_version` frontmatter, one line per type
    wiki/<type>/index.md               that type's rows `- [Title](../slug.md) — summary`
    wiki/<type>/<year>/index.md        only for a type whose section outgrows SECTION_MAX_BYTES: the type index then
                                       lists the years and each year file holds the rows (`../../slug.md`)

OKF v0.2 allows an `index.md` in any directory and the okf-check treats `index.md` as reserved by basename, so none of
these files is a page: no `type`, never scanned, counted, graphed or searched as a page. `lint.write_index` writes them
on every run and removes the ones that no longer apply (only files carrying the generated marker). This module is
pure: it renders text from entries and reads the files back; lint decides what goes in.
"""
from __future__ import annotations

import os
import re

from kb_distillery.core import links as page_links
from kb_distillery.core.schema import INDEX_REL, OKF_VERSION, WIKI_DIR, is_index_path

SECTION_MAX_BYTES = 40_000       # a section index above this is split by year (one level, never deeper)
QUERY_PAGES = 5                  # the pages a typical query reads after the index
MARK = "Generated by `src/kb_distillery/lint/lint.py`. Do not hand-edit."
UNDATED = "undated"
_YEAR = re.compile(r"^\s*['\"]?(\d{4})(?!\d)")
_YEAR_KEYS = ("year", "created", "date", "published")
_TAIL = re.compile(r"^(?: \([^()]*\))?(?: — (.*))?$")      # after the link: ` — summary` (an older index also had ` (maturity)`)
_H1 = re.compile(r"^# (.+)$", re.M)

# (type, section title, one-line description). Types a kb adds on its own follow, titled by their label.
SECTIONS = [
    ("topic", "Topics", "Theme hubs: one per area, linking the ideas and sources under it."),
    ("idea", "Ideas", "Concept notes: one claim or technique each, cross-linked."),
    ("question", "Open questions", "Questions with a status of open, partial or resolved."),
    ("course", "Courses", "Course hubs listing their lectures and notes."),
    ("series", "Series", "Series hubs grouping related posts or articles."),
    ("book", "Books", "Books, with the parts digested from them."),
    ("notebook", "Notebooks", "Handwritten notebooks, split into page ranges."),
    ("paper", "Papers", "Digested papers, one page each."),
    ("part", "Book parts", "Page ranges of a book, digested on their own."),
    ("lecture", "Lectures", "One page per class session."),
    ("article", "Articles", "Web articles and tutorials."),
    ("blog-post", "Blog posts", "One page per blog post."),
    ("video", "Videos", "Video digests."),
    ("ai-chat", "AI chats", "Saved AI chat conversations."),
    ("mail", "Mail", "Email threads."),
    ("person", "People", "People: researchers and collaborators, with their papers."),
    ("scope", "Scopes", "A bounded set of sources for a focused question."),
    ("distilled-think", "Distilled thinking (review)", "Distilled thinking notes waiting for review."),
]


def page_year(fm):
    """The four-digit year of a page (`year`, else `created`, `date`, `published`), or None."""
    for key in _YEAR_KEYS:
        m = _YEAR.match(str(fm.get(key) or ""))
        if m:
            return m.group(1)
    return None


def _count(n):
    return f"{n} page" + ("" if n == 1 else "s")


def _section_text(title, rows, back):
    out = [f"# {title}", "", f"> {MARK} Back to the [wiki index]({back}).", ""]
    out += rows
    return "\n".join(out) + "\n"


def _row(entry, up):
    s = entry.get("summary") or ""
    return "- " + page_links.page_link(entry["slug"], {entry["slug"]: entry.get("title") or ""}, up=up) + (f" — {s}" if s else "")


def render(entries, labels=None, order=()):
    """{repo-relative path: text} of the whole index. `entries` = [{slug, type, title, summary, year}] (`year` is a
    four-digit string or None); `labels` = {type: title} and `order` = the kb's
    type order, both for types outside SECTIONS (a kb's own types follow the built-in ones in its order)."""
    labels = labels or {}
    by_type = {}
    for e in entries:
        if isinstance(e["type"], str):            # a malformed `type:` has no section
            by_type.setdefault(e["type"], []).append(e)
    known = {t for t, _title, _d in SECTIONS}
    kb_order = list(order)
    sections = [(t, title, desc) for t, title, desc in SECTIONS]
    extra = sorted((t for t in by_type if t not in known),
                   key=lambda t: (t not in kb_order, kb_order.index(t) if t in kb_order else 0, t))
    sections += [(t, labels.get(t) or t.replace("-", " ").capitalize(), f"Pages of type `{t}`.") for t in extra]
    files = {}
    root_rows = []
    for t, title, desc in sections:
        group = sorted(by_type.get(t, ()), key=lambda e: e["slug"])
        if not group or not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", t):
            continue
        base = f"{WIKI_DIR}/{t}"
        text = _section_text(title, [_row(e, 1) for e in group], "../index.md")
        if len(text.encode("utf-8")) <= SECTION_MAX_BYTES:
            files[f"{base}/index.md"] = text
            note = _count(len(group))
        else:
            years = {}
            for e in group:
                years.setdefault(e.get("year") or UNDATED, []).append(e)
            names = sorted(years, key=lambda y: (y == UNDATED, "" if y == UNDATED else str(9999 - int(y))))     # newest first
            for y in names:
                files[f"{base}/{y}/index.md"] = _section_text(f"{title} — {y}", [_row(e, 2) for e in years[y]], "../../index.md")
            files[f"{base}/index.md"] = _section_text(
                title, [f"- [{y}]({y}/index.md) — {_count(len(years[y]))}" for y in names], "../index.md")
            note = f"{_count(len(group))}, by year"
        root_rows.append(f"- [{title}]({t}/index.md) — {note}. {desc}")
    files[INDEX_REL] = "\n".join(
        ["---", f"okf_version: {OKF_VERSION}", "---", "", "# Wiki index", "", f"> {MARK}", "",
         "Read this root first, then open only the one section you need; each section lists its pages, one per line.", ""]
        + root_rows) + "\n"
    return files


def index_files(root):
    """Repo-relative paths of every generated index file on disk: the root and each section index."""
    out = []
    base = os.path.join(root, WIKI_DIR)
    if os.path.isfile(os.path.join(root, INDEX_REL)):
        out.append(INDEX_REL)
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        if "index.md" in filenames and dirpath != base:
            rel = os.path.relpath(os.path.join(dirpath, "index.md"), root).replace(os.sep, "/")
            if is_index_path(rel):
                out.append(rel)
    return out


def is_generated_file(path):
    """True when the file at `path` carries the generated marker (a stale section index is removed only then)."""
    try:
        with open(path, encoding="utf-8") as f:
            return MARK in f.read(2000)
    except (OSError, UnicodeDecodeError):
        return False


def write(root, files):
    """Write `files` ({rel: text}) under `root`, then remove the generated section indexes that are not in it, and the
    folders that emptied. Returns the relative paths written. Touches nothing but files with the generated marker."""
    for rel, text in files.items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if os.path.isfile(path):
            with open(path, encoding="utf-8") as f:
                if f.read() == text:
                    continue
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    for rel in index_files(root):
        if rel == INDEX_REL or rel in files:
            continue
        path = os.path.join(root, rel)
        if not is_generated_file(path):
            continue
        os.remove(path)
        folder = os.path.dirname(path)
        for _ in range(2):                     # <type>/<year>/ then <type>/
            try:
                os.rmdir(folder)
            except OSError:
                break
            folder = os.path.dirname(folder)
    return sorted(files)


def _section_name(text):
    m = _H1.search(text)
    return m.group(1).split(" — ")[0].strip() if m else ""


def parse_rows(root):
    """{slug: {section, title, summary, file}} read from every section index (the rows `- [Title](../slug.md) — summary`).
    A pre-split flat root index (rows with `## Section` headings) still parses."""
    rows = {}
    for rel in index_files(root):
        try:
            with open(os.path.join(root, rel), encoding="utf-8") as f:
                text = f.read()
        except OSError:
            continue
        section = _section_name(text) if rel != INDEX_REL else ""
        for line in text.split("\n"):
            if line.startswith("## "):
                section = line[3:].strip()
                continue
            if not line.startswith("- "):
                continue
            m = page_links.INDEX_LINK.match(line, 2)
            if not m:
                continue
            title, slug, _anchor = page_links.link_parts(m)
            if slug == "index":                      # the back link and the section links are not pages
                continue
            tail = _TAIL.match(line[m.end():])
            rows[slug] = {"section": section, "title": title, "file": rel,
                          "summary": (tail.group(1) or "").strip() if tail else ""}
    return rows


def sizes(root):
    """{rel: bytes} of every generated index file on disk."""
    out = {}
    for rel in index_files(root):
        try:
            out[rel] = os.path.getsize(os.path.join(root, rel))
        except OSError:
            pass
    return out


def typical_query_bytes(root, avg_page_bytes):
    """Bytes a typical query reads: the root, one average section index, and QUERY_PAGES average pages."""
    sz = sizes(root)
    root_b = sz.get(INDEX_REL, 0)
    sections = [b for rel, b in sz.items() if rel != INDEX_REL]
    return root_b + (sum(sections) / len(sections) if sections else 0) + QUERY_PAGES * avg_page_bytes
