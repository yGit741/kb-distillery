"""Generate the frontend side of the flag registry from meta/flags.toml.

    python -m kb_distillery.config.flags.codegen           # write the files
    python -m kb_distillery.config.flags.codegen --check   # exit 1 when any generated file is stale (web-check, ship lanes)

Writes `src/kb_distillery/publish/cloudflare/worker/flags.gen.js` (runtime flag names for the private Worker), `web/src/flags/registry.gen.ts` (the typed `FlagName` union, metadata and a value per env) and
the share builds' route lists `web/src/routes/modules.share-{private,public}.ts`: the share core
screens plus every `screen.<id>` build flag that is on in that env. vite.config.ts aliases
`@/routes/modules` to one of them, so a screen whose flag is off is not in that bundle at all.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from kb_distillery.config.flags.registry import FLAGS_TOML, FlagError, Registry, load
from kb_distillery.config.resources import require_repo_root, resource   # generated files and tests are code: the explorer, not the vault

GEN_TS = Path("web/src/flags/registry.gen.ts")
GEN_WORKER = Path("src/kb_distillery/publish/cloudflare/worker/flags.gen.js")   # the private Worker accepts overrides for these names only
SHARE_ENVS = ("private", "public")
# Always in every share build: the read-only site itself. Everything else is opt-in by a screen.* flag.
SHARE_CORE_SCREENS = ("home", "graph", "pages")
HEADER = "// GENERATED by `pixi run flags-gen` (python -m kb_distillery.config.flags.codegen) from meta/flags.toml — do not edit.\n"


def modules_path(env: str) -> Path:
    return Path(f"web/src/routes/modules.share-{env}.ts")


def share_screens(reg: Registry, env: str) -> list[str]:
    flagged = [f.name.removeprefix("screen.") for f in reg.flags
               if f.kind == "build" and f.name.startswith("screen.") and f.value(env)]
    return list(SHARE_CORE_SCREENS) + sorted(set(flagged) - set(SHARE_CORE_SCREENS))


def render_registry(reg: Registry) -> str:
    meta = {f.name: {"description": f.description, "owner": f.owner, "created": f.created.isoformat(),
                     "expires": f.expires.isoformat(), "kind": f.kind, "default": f.default,
                     "envs": f.envs.model_dump()} for f in reg.flags}
    union = " | ".join(json.dumps(n) for n in reg.names()) or "never"
    return (HEADER
            + 'export type FlagEnv = "local" | "private" | "public";\n'
            + 'export type FlagKind = "runtime" | "build";\n'
            + f"export type FlagName = {union};\n\n"
            + "export interface FlagMeta {\n  description: string;\n  owner: string;\n  created: string;\n"
            + "  expires: string;\n  kind: FlagKind;\n  default: boolean;\n  envs: Record<FlagEnv, boolean>;\n}\n\n"
            + f"export const FLAG_NAMES: readonly FlagName[] = {json.dumps(reg.names())};\n\n"
            + f"export const FLAGS: Readonly<Record<FlagName, FlagMeta>> = {json.dumps(meta, indent=2)};\n")


def render_modules(reg: Registry, env: str) -> str:
    files = ", ".join(json.dumps(f"../features/{s}/index.tsx") for s in share_screens(reg, env))
    return (HEADER
            + 'import type { FeatureModule } from "./modules";\n\n'
            + f"/** Share build `{env}`: the core screens plus every screen.* flag on for {env}. Nothing else is imported. */\n"
            + f"export const modules = import.meta.glob<FeatureModule>([{files}], {{ eager: true }});\n")


def render_worker(reg: Registry) -> str:
    runtime = [f.name for f in reg.flags if f.kind == "runtime"]
    return (HEADER + "/** Runtime flags: the only names PUT /api/flags/<name> on the private site accepts. */\n"
            + f"export const RUNTIME_FLAGS = {json.dumps(runtime)};\n")


def outputs(reg: Registry) -> dict[Path, str]:
    out = {GEN_TS: render_registry(reg), GEN_WORKER: render_worker(reg)}
    out.update({modules_path(e): render_modules(reg, e) for e in SHARE_ENVS})
    return out


def _registry_for(root: Path) -> Path:
    """`<root>/meta/flags.toml` (a vault's own), else the base kit's `defaults/flags.toml` (the explorer's), else the
    registry this process resolved (kb_distillery.config.flags.registry.FLAGS_TOML)."""
    for p in (root / "meta" / "flags.toml", resource("kits/base/defaults") / "flags.toml"):
        if p.is_file():
            return p
    return FLAGS_TOML


def main(argv=None, root: Path | str | None = None) -> int:
    root = Path(root) if root is not None else require_repo_root("flags codegen")
    ap = argparse.ArgumentParser(prog="kb_distillery.config.flags.codegen", description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when a generated file is stale; write nothing")
    ap.add_argument("--flags", default=None, help="registry path (default meta/flags.toml)")
    args = ap.parse_args(argv)
    try:
        reg = load(args.flags or _registry_for(root))
    except FlagError as e:
        print(e, file=sys.stderr)
        return 2
    missing = sorted({s for e in SHARE_ENVS for s in share_screens(reg, e)
                      if not (root / f"web/src/features/{s}/index.tsx").is_file()})
    if missing:
        print("flags: screen flag(s) with no web/src/features/<id>/index.tsx: " + ", ".join(missing), file=sys.stderr)
        return 2
    stale = []
    for rel, text in outputs(reg).items():
        p = root / rel
        current = p.read_text(encoding="utf-8") if p.is_file() else None
        if current == text:
            continue
        stale.append(str(rel))
        if not args.check:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8", newline="\n")
    if args.check and stale:
        print("flags: stale generated file(s): " + ", ".join(stale) + " — run `pixi run flags-gen`", file=sys.stderr)
        return 1
    print(f"flags: {len(reg.flags)} flag(s); " + (f"wrote {', '.join(stale)}" if stale and not args.check else "generated files up to date"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
